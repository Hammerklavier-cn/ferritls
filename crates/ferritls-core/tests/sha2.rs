#[test]
fn sha2_streaming_consistency() {
    let data: Vec<u8> = (0u8..200).collect();
    let mut h = Sha256::new();
    for chunk in data.chunks(7) {
        h.update(chunk);
    }
    assert_eq!(
        common::to_hex(&h.finalize()),
        common::to_hex(&Sha256::one_shot(&data)),
        "streaming == one_shot"
    );
}

