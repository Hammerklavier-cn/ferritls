/// FIPS 180-4 §B/§C 官方多块示例（2026-09-07 与 FIPS 原文核对；
/// SHA-384 侧经 python hashlib 与 OpenSSL 3.2.4 双工具一致确认）。
#[test]
fn sha2_fips180_4_multiblock_examples() {
    let m56 = b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq";
    assert_eq!(m56.len(), 56, "FIPS 180-4 two-block message length");
    assert_hex(
        &Sha384::one_shot(m56),
        "3391fdddfc8dc7393707a65b1b4709397cf8b1d162af05abfe8f450de5f36bc6b0455a8520bc4e6f5fe95b1fe3c8452b",
        "SHA-384(two-block message)",
    );
    assert_hex(
        &Sha512::one_shot(m56),
        "204a8fc6dda82f0a0ced7beb8e08a41657c16ef468b228a8279be331a703c33596fd15c13b1b07f9aa1d3bea57789ca031ad85c7a71dd70354ec631238ca3445",
        "SHA-512(two-block message)",
    );
    // 百万字节 'a'（FIPS 180-4 官方示例；SHA-256/512 与原文示例值一致）。
    let million = vec![b'a'; 1_000_000];
    assert_hex(
        &Sha256::one_shot(&million),
        "cdc76e5c9914fb9281a1c7e284d73e67f1809a48a497200e046d39ccc7112cd0",
        "SHA-256(million a)",
    );
    assert_hex(
        &Sha384::one_shot(&million),
        "9d0e1809716474cb086e834e310a4a1ced149e9c00f248527972cec5704c2a5b07b8b3dc38ecc4ebae97ddd87f3d8985",
        "SHA-384(million a)",
    );
    assert_hex(
        &Sha512::one_shot(&million),
        "e718483d0ce769644e2e42c7bc15b4638e1f98b13b2044285632a803afa973ebde0ff244877ea60a4cb0432ce577c31beb009c5c2c49aa2e4eadb217ad8cc09b",
        "SHA-512(million a)",
    );
}

